function audit = buildGlobalTangentStationaryCompressionAudit(problem, ...
    trustedBounds,supportBounds,targetWaveIndices,modeCounts, ...
    stationaryDegree,referenceDegrees,paddingFactors,terrainScales, ...
    providerOrders,shouldRunTwoDimensionalControl,cacheDirectory, ...
    quadratureOrder,modeSource)
% Build the Milestone-10.2.5 global tangent stationary oracle.

configuration = struct("trustedBounds",trustedBounds, ...
    "supportBounds",supportBounds,"targetWaveIndices",targetWaveIndices, ...
    "modeCounts",modeCounts,"stationaryDegree",stationaryDegree, ...
    "referenceDegrees",referenceDegrees,"paddingFactors",paddingFactors, ...
    "terrainScales",terrainScales,"providerOrders",providerOrders, ...
    "shouldRunTwoDimensionalControl",shouldRunTwoDimensionalControl, ...
    "quadratureOrder",quadratureOrder,"modeSource",modeSource);
[cached,cache] = loadAuditCache(problem,cacheDirectory,configuration);
if ~isempty(cached)
    audit = cached;
    audit.cache = cache;
    return
end
buildTimer = tic;

factorization = polynomialFactorizationSweep(problem,trustedBounds, ...
    supportBounds,stationaryDegree,referenceDegrees,paddingFactors, ...
    quadratureOrder);
tolerance = struct("factorization",1e-12,"traceRank",1e-11, ...
    "provider",1e-11,"lift",1e-10,"stationary",1e-10, ...
    "projector",1e-8,"frequency",1e-8,"apv",1e-8, ...
    "bottom",1e-10,"strong",1e-5,"drift",1e-8, ...
    "compression",2);
factorizationPasses = all([factorization.results.dimensionDefect] == 0) ...
    && max([factorization.results.projectorDefect]) ...
        <= tolerance.factorization ...
    && max([factorization.results.tangentLiftTraceDefect]) ...
        <= tolerance.factorization ...
    && max([factorization.results.tangentLiftEnergyDefect]) ...
        <= tolerance.factorization ...
    && max([factorization.results.tangentLiftAPVDefect]) ...
        <= tolerance.lift ...
    && max([factorization.results.tangentTraceDefect]) ...
        <= tolerance.traceRank ...
    && max([factorization.results.traceConjugacyDefect]) ...
        <= tolerance.traceRank ...
    && all([factorization.results.rankStable]);

training = struct("wasAttempted",false);
validation = struct("wasAttempted",false);
if ~factorizationPasses
    classification = "global-tangent-factorization-blocker";
    diagnosis = "The polynomial stationary oracle does not admit the proposed factorization within tolerance.";
else
    baselineSupport = supportBounds(ceil(size(supportBounds,1)/2),:);
    baselineDegree = referenceDegrees(ceil(numel(referenceDegrees)/2));
    if modeSource == "analytic"
        training = analyticModalTraining(problem,trustedBounds, ...
            baselineSupport,targetWaveIndices,modeCounts, ...
            stationaryDegree,baselineDegree,paddingFactors(1), ...
            terrainScales,providerOrders(end),quadratureOrder,tolerance);
        if training.analyticControlPasses ...
                && (training.materiallyImproves || training.passes)
            validation = analyticValidation(problem,trustedBounds, ...
                supportBounds,targetWaveIndices, ...
                training.bestUnqualifiedInteriorModeCount, ...
                stationaryDegree,referenceDegrees,paddingFactors, ...
                terrainScales,providerOrders(end),quadratureOrder, ...
                tolerance);
        end
        [classification,diagnosis] = ...
            classifyAnalyticTraining(training,validation,tolerance);
    else
        training = modalTraining(problem,trustedBounds,baselineSupport, ...
            targetWaveIndices,modeCounts,stationaryDegree,baselineDegree, ...
            paddingFactors(1),terrainScales,providerOrders,quadratureOrder, ...
            tolerance);
        [classification,diagnosis] = classifyTraining(training,tolerance);
    end
end

audit = struct;
if modeSource == "analytic"
    audit.scope = ...
        "milestone-10.2.5.1-analytic-global-tangent-attribution";
    audit.nextScope = "milestone-10.2.5.1-stop-for-review";
else
    audit.scope = "milestone-10.2.5-global-tangent-stationary-compression";
    audit.nextScope = "milestone-10.2.5-stop-for-review";
end
audit.status = classification;
audit.classification = classification;
audit.diagnosis = diagnosis;
audit.factorization = factorization;
audit.training = training;
audit.validation = validation;
audit.twoDimensionalControl = struct("wasRequested", ...
    shouldRunTwoDimensionalControl,"wasAttempted",false);
audit.gates = struct("factorization",factorizationPasses, ...
    "training",isfield(training,"passes") && training.passes);
audit.requiredTolerance = tolerance;
audit.trustedModeBounds = trustedBounds;
audit.supportModeBounds = supportBounds;
audit.targetWaveModeIndices = targetWaveIndices;
audit.interiorGeostrophicModeCounts = modeCounts;
audit.stationaryReferenceDegree = stationaryDegree;
audit.primitiveReferenceDegrees = referenceDegrees;
audit.paddingFactors = paddingFactors;
audit.terrainScales = terrainScales;
audit.internalModesEVPOrders = providerOrders;
audit.modeSource = modeSource;
audit.internalModesEVPCommit = ...
    "df86687e91faa31bf65941299062d125a96904b1";
audit.cache = cache;
audit = saveAuditCache(audit,cacheDirectory,configuration,cache, ...
    toc(buildTimer));
end

function training = modalTraining(problem,trustedBounds,supportBounds, ...
    targetWaveIndices,modeCounts,stationaryDegree,referenceDegree,padding, ...
    terrainScales,providerOrders,quadratureOrder,tolerance)
layout = retainedLayout(problem,supportBounds);
[primitive,c] = buildGlobalSmallTerrainPrimitiveAudit(problem, ...
    referenceDegree,quadratureOrder,1e-3,horizontalLayout=layout, ...
    paddingFactor=padding,trustedModeBounds=trustedBounds, ...
    rejectTerrainNyquist=true,evaluationScales=terrainScales, ...
    shouldAuditTangent=false);
catalog = modalCatalog(problem,c,max([modeCounts;targetWaveIndices]), ...
    providerOrders);
flatWaves = waveColumns(c,catalog,targetWaveIndices,trustedBounds);
reference = continueReference(c,primitive,flatWaves,terrainScales, ...
    trustedBounds,referenceDegree,stationaryDegree);
results = repmat(emptyModalCompressionResult,numel(modeCounts),1);
for iCount = 1:numel(modeCounts)
    results(iCount) = modalCompressionResult(c,primitive,catalog, ...
        reference,trustedBounds,referenceDegree,stationaryDegree, ...
        targetWaveIndices,modeCounts(iCount),terrainScales(end));
end

passes = arrayfun(@(value)modalResultPasses(value,tolerance),results);
selected = find(passes,1);
if isempty(selected)
    score = [[results.stationaryRepresentationDefect].' ...
        [results.maximumProjectorDefect].' (1:numel(results)).'];
    [~,order] = sortrows(score,[1 2 3]);
    selected = order(1);
    frozenCount = NaN;
else
    frozenCount = modeCounts(selected);
end
training = struct("wasAttempted",true,"results",results, ...
    "selectedIndex",selected,"frozenInteriorModeCount",frozenCount, ...
    "bestUnqualifiedInteriorModeCount",modeCounts(selected), ...
    "passes",~isnan(frozenCount),"supportModeBounds",supportBounds, ...
    "primitiveReferenceDegree",referenceDegree, ...
    "paddingFactor",padding,"terrainScales",terrainScales, ...
    "provider",catalog.diagnostics);
end

function training = analyticModalTraining(problem,trustedBounds, ...
    supportBounds,targetWaveIndices,modeCounts,stationaryDegree, ...
    referenceDegree,padding,terrainScales,comparisonOrder, ...
    quadratureOrder,tolerance)
layout = retainedLayout(problem,supportBounds);
[primitive,c] = buildGlobalSmallTerrainPrimitiveAudit(problem, ...
    referenceDegree,quadratureOrder,1e-3,horizontalLayout=layout, ...
    paddingFactor=padding,trustedModeBounds=trustedBounds, ...
    rejectTerrainNyquist=true,evaluationScales=terrainScales, ...
    shouldAuditTangent=false);
[analyticCatalog,providerCatalog] = analyticModalCatalog(problem,c, ...
    max([modeCounts;targetWaveIndices]),comparisonOrder);
flatWaves = waveColumns(c,analyticCatalog,targetWaveIndices,trustedBounds);
reference = continueReference(c,primitive,flatWaves,terrainScales, ...
    trustedBounds,referenceDegree,stationaryDegree);
nCount = numel(modeCounts);
results = repmat(emptyModalCompressionResult,nCount,1);
providerResults = repmat(emptyModalCompressionResult,nCount,1);
verticalDifference = zeros(nCount,1);
propagatedDifference = zeros(nCount,1);
for iCount = 1:nCount
    [results(iCount),analyticSubspace] = modalCompressionResult( ...
        c,primitive,analyticCatalog,reference,trustedBounds, ...
        referenceDegree,stationaryDegree,targetWaveIndices, ...
        modeCounts(iCount),terrainScales(end));
    [providerResults(iCount),providerSubspace] = modalCompressionResult( ...
        c,primitive,providerCatalog,reference,trustedBounds, ...
        referenceDegree,stationaryDegree,targetWaveIndices, ...
        modeCounts(iCount),terrainScales(end));
    verticalDifference(iCount) = zeroTraceCatalogDifference( ...
        analyticCatalog,providerCatalog,modeCounts(iCount), ...
        c.quadrature.weight);
    propagatedDifference(iCount) = projectorDefect( ...
        analyticSubspace.stationary,providerSubspace.stationary, ...
        primitive.evaluatedDirections(end).E);
end

physicalPasses = arrayfun( ...
    @(value)modalPhysicalPasses(value,tolerance),results);
selected = find(physicalPasses,1);
if isempty(selected)
    score = [[results.stationaryRepresentationDefect].' ...
        [results.maximumProjectorDefect].' (1:nCount).'];
    [~,order] = sortrows(score,[1 2 3]);
    selected = order(1);
    frozenCount = NaN;
else
    frozenCount = modeCounts(selected);
end
stationaryDefect = [results.stationaryRepresentationDefect].';
monotonic = all(stationaryDefect(2:end) ...
    <=1.01*stationaryDefect(1:end-1));
improvementFactor = stationaryDefect(1) ...
    /max(min(stationaryDefect),realmin);
materiallyImproves = monotonic && improvementFactor >=4;
analyticControl = analyticCatalog.diagnostics.analyticControl;
analyticControl.maximumConjugacyDefect = ...
    analyticScalarConjugacyDefect(c,analyticCatalog,max(modeCounts));
analyticControlValues = cell2mat(struct2cell(analyticControl));
analyticControlPasses = max(analyticControlValues) <=1e-12;

training = struct("wasAttempted",true,"results",results, ...
    "providerResults",providerResults,"selectedIndex",selected, ...
    "frozenInteriorModeCount",frozenCount, ...
    "bestUnqualifiedInteriorModeCount",modeCounts(selected), ...
    "passes",~isnan(frozenCount),"supportModeBounds",supportBounds, ...
    "primitiveReferenceDegree",referenceDegree, ...
    "paddingFactor",padding,"terrainScales",terrainScales, ...
    "comparisonEVPOrder",comparisonOrder, ...
    "analyticControl",analyticControl, ...
    "analyticControlPasses",analyticControlPasses, ...
    "verticalProviderProjectorDefect",verticalDifference, ...
    "propagatedProviderProjectorDefect",propagatedDifference, ...
    "stationaryProjectorImprovementFactor",improvementFactor, ...
    "isMonotonic",monotonic, ...
    "materiallyImproves",materiallyImproves, ...
    "provider",providerCatalog.diagnostics);
end

function validation = analyticValidation(problem,trustedBounds, ...
    supportBounds,targetWaveIndices,count,stationaryDegree, ...
    referenceDegrees,paddingFactors,terrainScales,comparisonOrder, ...
    quadratureOrder,tolerance)
baselineSupport = supportBounds(ceil(size(supportBounds,1)/2),:);
baselineDegree = referenceDegrees(ceil(numel(referenceDegrees)/2));
baselinePadding = paddingFactors(1);
fullScale = terrainScales(end);
support = cell(size(supportBounds,1),1);
for iSupport = 1:size(supportBounds,1)
    support{iSupport} = analyticValidationCase(problem,trustedBounds, ...
        supportBounds(iSupport,:),targetWaveIndices,count, ...
        stationaryDegree,baselineDegree,baselinePadding,fullScale, ...
        comparisonOrder,quadratureOrder);
end
padding = cell(numel(paddingFactors),1);
for iPadding = 1:numel(paddingFactors)
    padding{iPadding} = analyticValidationCase(problem,trustedBounds, ...
        baselineSupport,targetWaveIndices,count,stationaryDegree, ...
        baselineDegree,paddingFactors(iPadding),fullScale, ...
        comparisonOrder,quadratureOrder);
end
reference = cell(numel(referenceDegrees),1);
for iReference = 1:numel(referenceDegrees)
    reference{iReference} = analyticValidationCase(problem, ...
        trustedBounds,baselineSupport,targetWaveIndices,count, ...
        stationaryDegree,referenceDegrees(iReference), ...
        baselinePadding,fullScale,comparisonOrder,quadratureOrder);
end
amplitude = analyticValidationCase(problem,trustedBounds, ...
    baselineSupport,targetWaveIndices,count,stationaryDegree, ...
    baselineDegree,baselinePadding,terrainScales,comparisonOrder, ...
    quadratureOrder);

allCases = [support;padding;reference;{amplitude}];
resultCells = cellfun(@(value)value.results,allCases, ...
    "UniformOutput",false);
allResults = vertcat(resultCells{:});
passes = arrayfun(@(value)modalPhysicalPasses(value,tolerance), ...
    allResults);
validation = struct("wasAttempted",true,"passes",all(passes), ...
    "interiorGeostrophicModeCount",count,"support",{support}, ...
    "padding",{padding},"reference",{reference}, ...
    "amplitude",amplitude, ...
    "maximumStationaryProjectorDefect", ...
        max([allResults.stationaryRepresentationDefect]), ...
    "maximumWaveProjectorDefect", ...
        max([allResults.maximumProjectorDefect]), ...
    "maximumAPVDefect",max([allResults.maximumAPVDefect]), ...
    "maximumBottomDefect",max([allResults.maximumBottomDefect]), ...
    "maximumStrongResidual",max([allResults.maximumStrongResidual]), ...
    "minimumCompressionFactor",min([allResults.compressionFactor]));
end

function value = analyticValidationCase(problem,trustedBounds, ...
    supportBounds,targetWaveIndices,count,stationaryDegree, ...
    referenceDegree,padding,terrainScales,comparisonOrder,quadratureOrder)
layout = retainedLayout(problem,supportBounds);
[primitive,c] = buildGlobalSmallTerrainPrimitiveAudit(problem, ...
    referenceDegree,quadratureOrder,1e-3,horizontalLayout=layout, ...
    paddingFactor=padding,trustedModeBounds=trustedBounds, ...
    rejectTerrainNyquist=true,evaluationScales=terrainScales, ...
    shouldAuditTangent=false);
[catalog,~] = analyticModalCatalog(problem,c, ...
    max([count;targetWaveIndices]),comparisonOrder);
flatWaves = waveColumns(c,catalog,targetWaveIndices,trustedBounds);
reference = continueReference(c,primitive,flatWaves,terrainScales, ...
    trustedBounds,referenceDegree,stationaryDegree);
results = repmat(emptyModalCompressionResult,numel(terrainScales),1);
for iScale = 1:numel(terrainScales)
    results(iScale) = modalCompressionResult(c,primitive,catalog, ...
        reference,trustedBounds,referenceDegree,stationaryDegree, ...
        targetWaveIndices,count,terrainScales(iScale));
end
value = struct("supportModeBounds",supportBounds, ...
    "primitiveReferenceDegree",referenceDegree, ...
    "paddingFactor",padding,"terrainScales",terrainScales, ...
    "results",results);
end

function [classification,diagnosis] = classifyTraining(training,tolerance)
selected = training.results(training.selectedIndex);
if ~selected.providerPasses
    classification = "global-tangent-provider-blocker";
    diagnosis = "The isolated mixed-boundary provider does not satisfy its endpoint, invariant, or order-convergence gates.";
elseif selected.liftRankDefect > 0 ...
        || selected.maximumLiftTraceDefect > tolerance.lift ...
        || selected.maximumLiftEnergyDefect > tolerance.lift
    classification = "global-tangent-modal-blocker";
    diagnosis = "The mixed-boundary modal space does not support a full-rank physical-energy lift solve.";
elseif training.passes
    classification = "training-pass-validation-pending";
    diagnosis = "A smallest acceptable interior modal count was frozen on the zonal training case; independent validation remains.";
elseif selected.stationaryRepresentationDefect ...
        < 0.5*training.results(1).stationaryRepresentationDefect ...
        || selected.maximumProjectorDefect ...
        < 0.5*training.results(1).maximumProjectorDefect
    classification = "global-tangent-seed";
    diagnosis = "The global tangent modal construction materially improves convergence but does not pass every training gate.";
else
    classification = "global-tangent-modal-blocker";
    diagnosis = "The exact factorization passes, but the mixed-boundary modal construction does not converge on the training case.";
end
end

function [classification,diagnosis] = ...
    classifyAnalyticTraining(training,validation,tolerance)
selected = training.results(training.selectedIndex);
providerDifference = training.propagatedProviderProjectorDefect( ...
    training.selectedIndex);
if ~training.analyticControlPasses
    classification = "analytic-control-blocker";
    diagnosis = "The exact constant-N family does not satisfy its endpoint, equation, normalization, invariant, or conjugacy controls.";
elseif training.passes && providerDifference > tolerance.projector
    classification = "provider-conditioning-blocker";
    diagnosis = "The analytic modal construction passes, but the pinned order-128 provider changes the propagated stationary projector beyond tolerance.";
elseif training.passes && validation.passes ...
        && selected.compressionFactor >= tolerance.compression
    classification = "analytic-modal-acceleration";
    diagnosis = "The exact mixed-boundary family passes the physical gates with factor-two compression; variable-stratification qualification remains separate.";
elseif training.passes && validation.passes
    classification = "analytic-modal-equivalent";
    diagnosis = "The exact mixed-boundary family passes the physical gates without factor-two compression; variable-stratification qualification remains separate.";
elseif training.materiallyImproves || training.passes
    classification = "analytic-modal-seed";
    diagnosis = "The exact mixed-boundary family improves the stationary projector monotonically by at least a factor of four but does not pass every physical gate.";
else
    classification = "analytic-modal-blocker";
    diagnosis = "Removing provider error does not produce a rapidly convergent compressed stationary span on the training problem.";
end
end

function value = modalResultPasses(result,tolerance)
value = modalPhysicalPasses(result,tolerance) ...
    && result.compressionFactor >= tolerance.compression;
end

function value = modalPhysicalPasses(result,tolerance)
value = result.providerPasses ...
    && result.liftRankDefect == 0 ...
    && result.maximumLiftTraceDefect <= tolerance.lift ...
    && result.maximumLiftEnergyDefect <= tolerance.lift ...
    && result.maximumLiftAPVDefect <= tolerance.lift ...
    && result.stationaryRepresentationDefect <= tolerance.projector ...
    && result.stationaryRowDefect <= tolerance.stationary ...
    && result.stationaryBottomTangencyDefect <= tolerance.stationary ...
    && result.stationaryConjugacyDefect <= tolerance.stationary ...
    && result.maximumProjectorDefect <= tolerance.projector ...
    && result.maximumFrequencyDefect <= tolerance.frequency ...
    && result.maximumAPVDefect <= tolerance.apv ...
    && result.maximumBottomDefect <= tolerance.bottom ...
    && result.maximumStrongResidual <= tolerance.strong;
end

function sweep = polynomialFactorizationSweep(problem,trustedBounds, ...
    supportBounds,stationaryDegree,referenceDegrees,paddingFactors, ...
    quadratureOrder)
nSupport = size(supportBounds,1);
nPadding = numel(paddingFactors);
results = repmat(emptyFactorizationResult,nSupport,nPadding);
degree = referenceDegrees(ceil(numel(referenceDegrees)/2));
for iSupport = 1:nSupport
    layout = retainedLayout(problem,supportBounds(iSupport,:));
    for iPadding = 1:nPadding
        [primitive,c] = buildGlobalSmallTerrainPrimitiveAudit( ...
            problem,degree,quadratureOrder,1e-3, ...
            horizontalLayout=layout, ...
            paddingFactor=paddingFactors(iPadding), ...
            trustedModeBounds=trustedBounds, ...
            rejectTerrainNyquist=true,evaluationScales=1, ...
            shouldAuditTangent=false);
        direction = primitive.evaluatedDirections(1);
        exact = constructCompleteStationarySpace(c,direction, ...
            trustedBounds,stationaryDegree,stationaryDegree,1);
        full = factorGlobalTangentStationarySpace( ...
            c,direction,exact,"full");
        trusted = factorGlobalTangentStationarySpace( ...
            c,direction,exact,"trusted");
        result = full.diagnostics;
        result.supportModeBounds = supportBounds(iSupport,:);
        result.paddingFactor = paddingFactors(iPadding);
        result.primitiveReferenceDegree = degree;
        result.trustedProjectorDefect = ...
            trusted.diagnostics.projectorDefect;
        result.trustedDimensionDefect = ...
            trusted.diagnostics.dimensionDefect;
        result.traceRank = full.trace.rank;
        result.numberOfTraceCoordinates = ...
            size(full.trace.tangentBasis,1)-1;
        result.numberOfTangentTraceCoordinates = ...
            size(full.trace.tangentBasis,2);
        result.numberOfNonTangentTraceCoordinates = ...
            size(full.trace.complementBasis,2);
        result.minimumLiftSingularValue = ...
            full.solvers.tangent.minimumSingularValue;
        result.liftConditionNumber = ...
            full.solvers.tangent.conditionNumber;
        results(iSupport,iPadding) = result;
    end
end
sweep = struct("results",results,"referenceDegree",degree, ...
    "maximumProjectorDefect",max([results.projectorDefect]), ...
    "maximumTrustedProjectorDefect", ...
        max([results.trustedProjectorDefect]), ...
    "maximumDimensionDefect",max([results.dimensionDefect]), ...
    "allRanksStable",all([results.rankStable]));
end

function catalog = modalCatalog(problem,c,count,orders)
kappa = hypot(c.horizontalLayout.k,c.horizontalLayout.l);
uniqueKappa = unique(kappa(kappa > 0),"sorted");
high = cell(numel(uniqueKappa),1);
low = cell(numel(uniqueKappa),1);
difference = zeros(numel(uniqueKappa),1);
endpoint = zeros(numel(uniqueKappa),1);
invariant = zeros(numel(uniqueKappa),1);
analytic = zeros(numel(uniqueKappa),1);
for iKappa = 1:numel(uniqueKappa)
    boundaryHigh = buildBoundaryCompleteVerticalReferenceFamily( ...
        problem,uniqueKappa(iKappa),count,Inf,orders(end), ...
        c.quadrature.xi);
    boundaryLow = buildBoundaryCompleteVerticalReferenceFamily( ...
        problem,uniqueKappa(iKappa),count,Inf,orders(end-1), ...
        c.quadrature.xi);
    zeroHigh = buildZeroTraceGeostrophicVerticalFamily(problem, ...
        uniqueKappa(iKappa),count,orders(end),c.quadrature.xi, ...
        c.quadrature.weight);
    zeroLow = buildZeroTraceGeostrophicVerticalFamily(problem, ...
        uniqueKappa(iKappa),count,orders(end-1),c.quadrature.xi, ...
        c.quadrature.weight);
    high{iKappa} = struct("wave",boundaryHigh.wave, ...
        "bottom",boundaryHigh.bottom,"zeroTrace",zeroHigh);
    low{iKappa} = struct("wave",boundaryLow.wave, ...
        "bottom",boundaryLow.bottom,"zeroTrace",zeroLow);
    difference(iKappa) = maximumSubspaceDifference( ...
        high{iKappa},low{iKappa},c.quadrature.weight);
    endpoint(iKappa) = max([zeroHigh.diagnostics.bottomEndpointDefect, ...
        zeroHigh.diagnostics.surfaceEndpointDefect, ...
        boundaryHigh.diagnostics.waveEndpointDefect, ...
        boundaryHigh.diagnostics.bottomAPVDefect, ...
        boundaryHigh.diagnostics.bottomValueDefect]);
    invariant(iKappa) = max([ ...
        zeroHigh.diagnostics.energyDiagonalizationDefect, ...
        zeroHigh.diagnostics.enstrophyDiagonalizationDefect]);
    analytic(iKappa) = zeroHigh.diagnostics. ...
        constantStratificationAnalyticDefect;
end
catalog = struct("kappa",uniqueKappa,"family",{high}, ...
    "diagnostics",struct("providerDifference",max(difference), ...
    "maximumEndpointDefect",max(endpoint), ...
    "maximumInvariantDefect",max(invariant), ...
    "maximumAnalyticDefect",max(analytic),"orders",orders));
end

function [analyticCatalog,providerCatalog] = analyticModalCatalog( ...
    problem,c,count,comparisonOrder)
kappa = hypot(c.horizontalLayout.k,c.horizontalLayout.l);
uniqueKappa = unique(kappa(kappa > 0),"sorted");
analyticFamily = cell(numel(uniqueKappa),1);
providerFamily = cell(numel(uniqueKappa),1);
providerDifference = zeros(numel(uniqueKappa),1);
analyticEndpoint = zeros(numel(uniqueKappa),1);
analyticEquation = zeros(numel(uniqueKappa),1);
analyticNormalization = zeros(numel(uniqueKappa),1);
analyticEnergy = zeros(numel(uniqueKappa),1);
analyticEnstrophy = zeros(numel(uniqueKappa),1);
providerEndpoint = zeros(numel(uniqueKappa),1);
providerInvariant = zeros(numel(uniqueKappa),1);
providerAnalytic = zeros(numel(uniqueKappa),1);
for iKappa = 1:numel(uniqueKappa)
    boundary = buildBoundaryCompleteVerticalReferenceFamily( ...
        problem,uniqueKappa(iKappa),count,Inf,comparisonOrder, ...
        c.quadrature.xi);
    analyticZero = ...
        buildAnalyticZeroTraceGeostrophicVerticalFamily( ...
        problem,uniqueKappa(iKappa),count,c.quadrature.xi, ...
        c.quadrature.weight);
    providerZero = buildZeroTraceGeostrophicVerticalFamily(problem, ...
        uniqueKappa(iKappa),count,comparisonOrder,c.quadrature.xi, ...
        c.quadrature.weight);
    analyticFamily{iKappa} = struct("wave",boundary.wave, ...
        "bottom",boundary.bottom,"zeroTrace",analyticZero);
    providerFamily{iKappa} = struct("wave",boundary.wave, ...
        "bottom",boundary.bottom,"zeroTrace",providerZero);
    providerDifference(iKappa) = subspaceDifference( ...
        analyticZero.F,providerZero.F,c.quadrature.weight);
    analyticEndpoint(iKappa) = max([ ...
        analyticZero.diagnostics.bottomEndpointDefect, ...
        analyticZero.diagnostics.surfaceEndpointDefect]);
    analyticEquation(iKappa) = ...
        analyticZero.diagnostics.differentialEquationDefect;
    analyticNormalization(iKappa) = ...
        analyticZero.diagnostics.normalizationDefect;
    analyticEnergy(iKappa) = ...
        analyticZero.diagnostics.energyDiagonalizationDefect;
    analyticEnstrophy(iKappa) = ...
        analyticZero.diagnostics.enstrophyDiagonalizationDefect;
    providerEndpoint(iKappa) = max([ ...
        providerZero.diagnostics.bottomEndpointDefect, ...
        providerZero.diagnostics.surfaceEndpointDefect]);
    providerInvariant(iKappa) = max([ ...
        providerZero.diagnostics.energyDiagonalizationDefect, ...
        providerZero.diagnostics.enstrophyDiagonalizationDefect]);
    providerAnalytic(iKappa) = providerZero.diagnostics. ...
        constantStratificationAnalyticDefect;
end
analyticControl = struct( ...
    "maximumEndpointDefect",max(analyticEndpoint), ...
    "maximumDifferentialEquationDefect",max(analyticEquation), ...
    "maximumNormalizationDefect",max(analyticNormalization), ...
    "maximumEnergyDiagonalizationDefect",max(analyticEnergy), ...
    "maximumEnstrophyDiagonalizationDefect",max(analyticEnstrophy));
analyticCatalog = struct("kappa",uniqueKappa, ...
    "family",{analyticFamily},"diagnostics",struct( ...
    "providerDifference",0, ...
    "maximumEndpointDefect",max(analyticEndpoint), ...
    "maximumInvariantDefect",max([analyticEnergy analyticEnstrophy], ...
        [],"all"),"maximumAnalyticDefect",0, ...
    "comparisonOrder",comparisonOrder, ...
    "verticalProviderDifference",max(providerDifference), ...
    "analyticControl",analyticControl));
providerCatalog = struct("kappa",uniqueKappa, ...
    "family",{providerFamily},"diagnostics",struct( ...
    "providerDifference",0, ...
