function value = analyticScalarConjugacyDefect(c,catalog,count)
scalar = zeroTraceModalScalar(c,catalog,count);
nonzero = find(hypot(c.horizontalLayout.k,c.horizontalLayout.l) > 0);
conjugate = zeros(numel(nonzero)*count,1);
for iHorizontal = 1:numel(nonzero)
    kMode = c.horizontalLayout.kMode(nonzero(iHorizontal));
    lMode = c.horizontalLayout.lMode(nonzero(iHorizontal));
    partner = find(c.horizontalLayout.kMode(nonzero) == -kMode ...
        & c.horizontalLayout.lMode(nonzero) == -lMode,1);
    if isempty(partner)
        error("WVTerrainEnergyGalerkin:IncompleteAnalyticConjugateLayout", ...
            "Every analytic mixed-boundary Fourier mode needs its signed conjugate.")
    end
    columns = (iHorizontal-1)*count+(1:count);
    conjugate(columns) = (partner-1)*count+(1:count);
end
fields = ["values" "valuesXi" "valuesX" "valuesY"];
value = 0;
for field = fields
    values = scalar.(field);
    first = values(:,conjugate);
    second = conj(values);
    value = max(value,norm(first-second,"fro") ...
        /max(norm(first,"fro")+norm(second,"fro"),realmin));
end
end

function [result,subspace] = modalCompressionResult( ...
    c,primitive,catalog,reference, ...
    trustedBounds,referenceDegree,stationaryDegree,targetWaveIndices, ...
    count,terrainScale)
iDirection = find(abs(primitive.evaluationScales-terrainScale) ...
    <=100*eps*max(abs(terrainScale),1),1);
if isempty(iDirection)
    error("WVTerrainEnergyGalerkin:UnavailableGlobalTangentTerrainScale", ...
        "terrainScale must be one of the primitive evaluation scales.")
end
direction = primitive.evaluatedDirections(iDirection);
if isfield(reference,"history") && numel(reference.history) > 1
    referenceAtScale = reference.history(iDirection);
else
    referenceAtScale = reference;
end
exact = constructCompleteStationarySpace(c,direction,trustedBounds, ...
    referenceDegree,stationaryDegree,terrainScale);
polynomialFactor = factorGlobalTangentStationarySpace( ...
    c,direction,exact,"full");
zeroScalar = zeroTraceModalScalar(c,catalog,count);
zeroScalar.terrainScale = terrainScale;
[zeroStates,zeroRepresentation] = projectGeostrophicState(c,zeroScalar);
bottomScalar = bottomPivotScalar(c,catalog, ...
    polynomialFactor.trace.selectedHorizontal);
bottomScalar.terrainScale = terrainScale;

tangentSeed = combineScalar(bottomScalar, ...
    polynomialFactor.trace.tangentBasis);
[tangentSeedStates,tangentSeedRepresentation] = ...
    projectGeostrophicState(c,tangentSeed);
[tangentStates,~,tangentSolve] = energyMinimalLifts( ...
    zeroStates,zeroScalar,tangentSeedStates,tangentSeed,direction.E);

nonTangentSeed = combineScalar(bottomScalar, ...
    polynomialFactor.trace.complementBasis);
[nonTangentSeedStates,nonTangentSeedRepresentation] = ...
    projectGeostrophicState(c,nonTangentSeed);
[nonTangentStates,nonTangentScalar,nonTangentSolve] = ...
    energyMinimalLifts(zeroStates,zeroScalar, ...
    nonTangentSeedStates,nonTangentSeed,direction.E);

stationaryMean = stationaryMeanColumns(c,catalog,count);
[stationary,stationaryOrthonormalization] = ...
    energyOrthonormalizeColumns( ...
    [zeroStates tangentStates stationaryMean],direction.E);
if ~isempty(nonTangentStates)
    nonTangentStates = nonTangentStates-stationary ...
        *(stationary'*direction.E*nonTangentStates);
    [nonTangentStates,~, ...
        nonTangentOrthonormalization] = energyOrthonormalize( ...
        nonTangentStates,nonTangentScalar,direction.E);
else
    nonTangentOrthonormalization = emptyOrthonormalization;
end

waves = waveColumns(c,catalog,targetWaveIndices,[Inf Inf]);
mean = inertialMeanColumns(c,catalog,count);
rawAmbient = [waves stationary nonTangentStates mean];
[ambient,ambientRank] = energyOrthonormalizeColumns( ...
    rawAmbient,direction.E);
dense = reducedPhysicalEigensystem( ...
    ambient,stationary,direction);
selected = selectByOverlap(dense.vectors,referenceAtScale.basis, ...
    direction.E,size(referenceAtScale.basis,2));
basis = energyNormalizeColumns(dense.vectors(:,selected),direction.E);
frequency = columnRayleighQuotients( ...
    basis,direction.E,1i*direction.J);
physical = physicalDiagnostics(c,direction,basis,frequency);

stationaryRepresentation = exact.trustedBasis ...
    -stationary*(stationary'*direction.E*exact.trustedBasis);
R = chol((direction.E+direction.E')/2);
stationaryRepresentationDefect = norm(R*stationaryRepresentation,"fro") ...
    /max(norm(R*exact.trustedBasis,"fro"),realmin);
liftAPV = norm(zeroStates'*direction.E*tangentStates,"fro") ...
    /max(norm(zeroStates,"fro")*norm(direction.E,"fro") ...
    *norm(tangentStates,"fro"),realmin);
provider = catalog.diagnostics;
result = emptyModalCompressionResult;
result.interiorGeostrophicModeCount = count;
result.numberOfModalCoordinates = size(ambient,2);
result.numberOfPrimitiveCoordinates = size(direction.E,1);
result.compressionFactor = size(direction.E,1)/size(ambient,2);
result.numberOfStationaryCoordinates = size(stationary,2);
result.numberOfTangentTraceCoordinates = size(tangentStates,2);
result.numberOfNonTangentTraceCoordinates = size(nonTangentStates,2);
result.providerPasses = provider.providerDifference <=1e-11 ...
    && provider.maximumEndpointDefect <=1e-11 ...
    && provider.maximumInvariantDefect <=1e-11 ...
    && (isnan(provider.maximumAnalyticDefect) ...
    || provider.maximumAnalyticDefect <=1e-11);
result.liftRankDefect = tangentSolve.rankDefect ...
    +nonTangentSolve.rankDefect;
result.maximumLiftTraceDefect = max( ...
    tangentSolve.traceDefect,nonTangentSolve.traceDefect);
result.maximumLiftEnergyDefect = max( ...
    tangentSolve.energyDefect,nonTangentSolve.energyDefect);
result.maximumLiftAPVDefect = liftAPV;
result.stationaryRepresentationDefect = ...
    stationaryRepresentationDefect;
result.stationaryRowDefect = normalizedProduct( ...
    direction.J,stationary);
result.stationaryBottomTangencyDefect = normalizedProduct( ...
    direction.R,stationary);
result.stationaryConjugacyDefect = subspaceConjugacyDefect( ...
    stationary,direction.E,c.coordinateConjugateIndex);
result.maximumProjectorDefect = projectorDefect( ...
    basis,referenceAtScale.basis,direction.E);
result.maximumFrequencyDefect = sortedFrequencyDefect( ...
    frequency,referenceAtScale.frequency);
result.maximumRitzResidual = physical.maximumRitzResidual;
result.maximumAPVDefect = physical.maximumAPVDefect;
result.maximumBottomDefect = physical.maximumBottomDefect;
result.maximumStrongResidual = physical.maximumStrongResidual;
result.energyHermitianDefect = norm(direction.E-direction.E',"fro") ...
    /max(norm(direction.E,"fro"),realmin);
result.exchangeSkewHermitianDefect = ...
    norm(direction.J+direction.J',"fro") ...
    /max(norm(direction.J,"fro"),realmin);
result.ambientRankDefect = ambientRank.rankDefect;
result.minimumAmbientSingularValue = ...
    ambientRank.minimumSingularValue;
result.liftDiagnostics = struct("tangent",tangentSolve, ...
    "nonTangent",nonTangentSolve, ...
    "stationaryOrthonormalization",stationaryOrthonormalization, ...
    "nonTangentOrthonormalization",nonTangentOrthonormalization);
result.representation = struct("zeroTrace",zeroRepresentation, ...
    "tangentSeed",tangentSeedRepresentation, ...
    "nonTangentSeed",nonTangentSeedRepresentation);
subspace = struct("stationary",stationary,"dynamical",basis, ...
    "ambient",ambient);
end

function scalar = zeroTraceModalScalar(c,catalog,count)
nGrid = c.nXY*c.nZ;
nColumns = nnz(hypot(c.horizontalLayout.k, ...
    c.horizontalLayout.l) > 0)*count;
scalar = emptyScalar(nGrid,c.nXY,nColumns);
column = 0;
for iHorizontal = 1:c.nK
    k = c.horizontalLayout.k(iHorizontal);
    l = c.horizontalLayout.l(iHorizontal);
    kappa = hypot(k,l);
    if kappa == 0
        continue
    end
    family = catalogFamily(catalog,kappa);
    for iMode = 1:count
        column = column+1;
        F = family.zeroTrace.F(:,iMode);
        Fz = family.zeroTrace.Fz(:,iMode);
        scalar.values(:,column) = kron(F,c.phase(:,iHorizontal));
        scalar.valuesXi(:,column) = kron(Fz,c.phase(:,iHorizontal));
        scalar.valuesX(:,column) = 1i*k*scalar.values(:,column);
        scalar.valuesY(:,column) = 1i*l*scalar.values(:,column);
    end
end
scalar.terrainScale = 1;
end

function scalar = bottomPivotScalar(c,catalog,selected)
nGrid = c.nXY*c.nZ;
nColumns = numel(selected);
scalar = emptyScalar(nGrid,c.nXY,nColumns);
[~,iBottom] = min(c.quadrature.xi);
for iSelected = 1:nColumns
    iHorizontal = selected(iSelected);
    k = c.horizontalLayout.k(iHorizontal);
    l = c.horizontalLayout.l(iHorizontal);
    kappa = hypot(k,l);
    if kappa == 0
        continue
    end
    family = catalogFamily(catalog,kappa);
    F = family.bottom.psi;
    Fz = -(c.wvt.N2Function(c.quadrature.xi)/c.wvt.f) ...
        .*family.bottom.eta;
    normalization = F(iBottom);
    if abs(normalization) <=100*eps*max(abs(F),[],"all")
        error("WVTerrainEnergyGalerkin:GlobalTangentBottomPivotFailure", ...
            "The public bottom inversion has a vanishing streamfunction trace.")
    end
    F = F/normalization;
    Fz = Fz/normalization;
    scalar.values(:,iSelected) = kron(F,c.phase(:,iHorizontal));
    scalar.valuesXi(:,iSelected) = kron(Fz,c.phase(:,iHorizontal));
    scalar.valuesX(:,iSelected) = 1i*k*scalar.values(:,iSelected);
    scalar.valuesY(:,iSelected) = 1i*l*scalar.values(:,iSelected);
    scalar.bottomValues(:,iSelected) = c.phase(:,iHorizontal);
end
scalar.terrainScale = 1;
end

function scalar = emptyScalar(nGrid,nBottom,nColumns)
scalar = struct("values",zeros(nGrid,nColumns), ...
    "valuesXi",zeros(nGrid,nColumns), ...
    "valuesX",zeros(nGrid,nColumns), ...
    "valuesY",zeros(nGrid,nColumns), ...
    "bottomValues",zeros(nBottom,nColumns), ...
    "coefficientBasis",eye(nColumns),"terrainScale",1);
end

function scalar = combineScalar(scalar,transform)
fields = ["values","valuesXi","valuesX","valuesY", ...
    "bottomValues","coefficientBasis"];
for field = fields
    scalar.(field) = scalar.(field)*transform;
end
end

function family = catalogFamily(catalog,kappa)
index = find(abs(catalog.kappa-kappa) ...
    <=100*eps*max(kappa,1),1);
family = catalog.family{index};
end

function difference = maximumSubspaceDifference(high,low,weight)
wave = subspaceDifference(high.wave.F,low.wave.F,weight);
zero = subspaceDifference( ...
    high.zeroTrace.F,low.zeroTrace.F,weight);
bottom = subspaceDifference( ...
    high.bottom.psi,low.bottom.psi,weight);
difference = max([wave zero bottom]);
end

function value = subspaceDifference(first,second,weight)
[first,~,~] = svd(sqrt(weight).*first,"econ");
[second,~,~] = svd(sqrt(weight).*second,"econ");
value = norm(first*first'-second*second',"fro") ...
    /max(norm(first*first',"fro")+norm(second*second',"fro"),realmin);
end

function [states,scalar,diagnostics] = energyMinimalLifts( ...
    zeroStates,zeroScalar,seedStates,seedScalar,E)
if isempty(seedStates)
    states = seedStates;
    scalar = seedScalar;
    diagnostics = emptyLiftDiagnostics;
    diagnostics.rank = size(zeroStates,2);
    return
end
R = chol((E+E')/2);
whitenedZero = R*zeroStates;
[U,S,V] = svd(whitenedZero,"econ");
singularValues = diag(S);
tolerance = max(size(whitenedZero))*eps(max(singularValues))*100;
rankValue = nnz(singularValues > tolerance);
rankDefect = size(zeroStates,2)-rankValue;
if rankDefect > 0
    states = seedStates;
    scalar = seedScalar;
    diagnostics = emptyLiftDiagnostics;
    diagnostics.rank = rankValue;
    diagnostics.rankDefect = rankDefect;
    diagnostics.singularValues = singularValues;
    return
end
correction = -V*((U'*(R*seedStates))./singularValues);
states = seedStates+zeroStates*correction;
scalar = seedScalar;
fields = ["values","valuesXi","valuesX","valuesY", ...
    "bottomValues"];
for field = fields
    scalar.(field) = seedScalar.(field)+zeroScalar.(field)*correction;
end
scalar.coefficientBasis = eye(size(scalar.values,2));
traceScale = norm(seedScalar.bottomValues,"fro");
energyScale = norm(zeroStates,"fro")*norm(E,"fro") ...
    *norm(states,"fro");
diagnostics = struct("rank",rankValue,"rankDefect",0, ...
    "singularValues",singularValues, ...
    "minimumSingularValue",singularValues(end), ...
    "conditionNumber",singularValues(1)/singularValues(end), ...
    "traceDefect",norm(scalar.bottomValues ...
        -seedScalar.bottomValues,"fro")/max(traceScale,realmin), ...
    "energyDefect",norm(zeroStates'*E*states,"fro") ...
        /max(energyScale,realmin));
end

function value = emptyLiftDiagnostics
value = struct("rank",0,"rankDefect",0, ...
    "singularValues",zeros(0,1),"minimumSingularValue",NaN, ...
    "conditionNumber",NaN,"traceDefect",0,"energyDefect",0);
end

function [states,scalar,diagnostics] = energyOrthonormalize(states,scalar,E)
[states,diagnostics,transform] = energyOrthonormalizeColumns(states,E);
fields = ["values","valuesXi","valuesX","valuesY", ...
    "bottomValues"];
for field = fields
    scalar.(field) = scalar.(field)*transform;
end
scalar.coefficientBasis = eye(size(states,2));
end

function [states,diagnostics,transform] = energyOrthonormalizeColumns(states,E)
if isempty(states)
    transform = zeros(0);
    diagnostics = emptyOrthonormalization;
    return
end
R = chol((E+E')/2);
[~,S,V] = svd(R*states,"econ");
singularValues = diag(S);
tolerance = max(size(states))*eps(max(singularValues))*100;
rankValue = nnz(singularValues > tolerance);
transform = V(:,1:rankValue)./singularValues(1:rankValue).';
states = states*transform;
diagnostics = struct("rank",rankValue, ...
    "rankDefect",size(V,2)-rankValue, ...
    "singularValues",singularValues, ...
    "minimumSingularValue",singularValues(rankValue), ...
    "conditionNumber",singularValues(1)/singularValues(rankValue), ...
    "defect",norm(states'*E*states-eye(rankValue),"fro") ...
        /sqrt(rankValue));
end

function value = emptyOrthonormalization
value = struct("rank",0,"rankDefect",0, ...
    "singularValues",zeros(0,1),"minimumSingularValue",NaN, ...
    "conditionNumber",NaN,"defect",0);
end

function [G,diagnostics] = projectGeostrophicState(c,scalar)
H3 = scalar.terrainScale*repmat(c.H,c.nZ,1);
HX3 = scalar.terrainScale*repmat(c.HX,c.nZ,1);
HY3 = scalar.terrainScale*repmat(c.HY,c.nZ,1);
gamma = 1-H3;
gammaX = -HX3;
gammaY = -HY3;
N2 = c.wvt.N2Function(gamma.*c.xiGrid);
if isscalar(N2)
    N2 = repmat(N2,size(c.xiGrid));
end
N2 = N2(:);
u = -gamma.*scalar.valuesY+c.xiGrid.*gammaY.*scalar.valuesXi;
v = gamma.*scalar.valuesX-c.xiGrid.*gammaX.*scalar.valuesXi;
w = c.xiGrid.*(gammaX.*scalar.valuesY-gammaY.*scalar.valuesX);
eta = -c.wvt.f*scalar.valuesXi./(gamma.*N2);
[uColumns,vColumns,wColumns,etaColumns] = componentColumns(c);
raw = zeros(c.nX,size(u,2));
raw(uColumns,:) = weightedFit(c.Ru(:,uColumns),u,c.volumeWeight);
raw(vColumns,:) = weightedFit(c.Rv(:,vColumns),v,c.volumeWeight);
raw(wColumns,:) = weightedFit(c.Rwh(:,wColumns),w,c.volumeWeight);
raw(etaColumns,:) = weightedFit( ...
    c.Reta(:,etaColumns),eta,c.volumeWeight);
G = c.N'*raw;
representedRaw = c.N*G;
represented = [c.Ru*representedRaw,c.Rv*representedRaw, ...
    c.Rwh*representedRaw,c.Reta*representedRaw];
targets = [u,v,w,eta];
diagnostics = struct("rawCoordinateDefect", ...
    relativeDifference(representedRaw,raw), ...
    "maximumDefect",relativeDifference(represented,targets), ...
    "continuityDefect",norm(c.continuity*representedRaw,"fro") ...
        /max(norm(c.continuity,"fro") ...
        *norm(representedRaw,"fro"),realmin));
end

function columns = waveColumns(c,catalog,modeIndices,bounds)
columns = zeros(size(c.N,2),0);
for iHorizontal = 1:c.nK
    if abs(c.horizontalLayout.kMode(iHorizontal)) > bounds(1) ...
            || abs(c.horizontalLayout.lMode(iHorizontal)) > bounds(2)
        continue
    end
    k = c.horizontalLayout.k(iHorizontal);
    l = c.horizontalLayout.l(iHorizontal);
    kappa = hypot(k,l);
    if kappa == 0
        continue
    end
    family = catalogFamily(catalog,kappa);
    for iMode = reshape(modeIndices,1,[])
        for sigma = [-1 1]
            omega = family.wave.omega(iMode);
            h = family.wave.h(iMode);
            F = family.wave.F(:,iMode);
            G = family.wave.G(:,iMode);
            state = struct( ...
                "u",(k*omega-sigma*1i*c.wvt.f*l) ...
                    /(omega*kappa)*F, ...
                "v",(l*omega+sigma*1i*c.wvt.f*k) ...
                    /(omega*kappa)*F, ...
                "w",-1i*kappa*h*G, ...
                "eta",-sigma*kappa*h/omega*G);
            columns(:,end+1) = embedState( ...
                c,iHorizontal,state); %#ok<AGROW>
        end
    end
end
end

function columns = inertialMeanColumns(c,catalog,count)
iHorizontal = find(c.horizontalLayout.kMode == 0 ...
    & c.horizontalLayout.lMode == 0,1);
if isempty(iHorizontal)
    columns = zeros(size(c.N,2),0);
    return
end
family = catalog.family{1};
constant = ones(size(c.quadrature.xi));
columns = zeros(size(c.N,2),0);
profiles = [constant family.wave.F(:,1:min(count, ...
    size(family.wave.F,2)))];
for iProfile = 1:size(profiles,2)
    for sigma = [-1 1]
        state = struct("u",profiles(:,iProfile), ...
            "v",sigma*1i*profiles(:,iProfile), ...
            "w",zeros(size(constant)),"eta",zeros(size(constant)));
        columns(:,end+1) = embedState( ...
            c,iHorizontal,state); %#ok<AGROW>
    end
end
end

function columns = stationaryMeanColumns(c,catalog,count)
iHorizontal = find(c.horizontalLayout.kMode == 0 ...
    & c.horizontalLayout.lMode == 0,1);
if isempty(iHorizontal)
    columns = zeros(size(c.N,2),0);
    return
end
family = catalog.family{1};
constant = ones(size(c.quadrature.xi));
columns = zeros(size(c.N,2),0);
etaProfiles = family.zeroTrace.eta(:,1:min(count, ...
    size(family.zeroTrace.eta,2)));
for iProfile = 1:size(etaProfiles,2)
    state = struct("u",zeros(size(constant)), ...
        "v",zeros(size(constant)),"w",zeros(size(constant)), ...
        "eta",etaProfiles(:,iProfile));
    columns(:,end+1) = embedState(c,iHorizontal,state); %#ok<AGROW>
end
chi = -c.quadrature.xi/c.wvt.Lz;
state = struct("u",zeros(size(chi)),"v",zeros(size(chi)), ...
    "w",zeros(size(chi)),"eta",chi);
columns(:,end+1) = embedState(c,iHorizontal,state);
end

function reference = continueReference(c,primitive,seed,scales,trusted, ...
    fullDegree,trustedDegree)
previous = energyNormalizeColumns(seed,primitive.evaluatedDirections(1).E);
history = repmat(struct("basis",zeros(0), ...
    "frequency",zeros(0,1)),numel(scales),1);
for iScale = 1:numel(scales)
    direction = primitive.evaluatedDirections(iScale);
    stationary = constructCompleteStationarySpace(c,direction, ...
        trusted,fullDegree,trustedDegree,scales(iScale));
    dense = physicalEigensystem(direction,stationary.trustedBasis);
    selected = selectByOverlap(dense.vectors,previous,direction.E, ...
        size(previous,2));
    previous = energyNormalizeColumns( ...
        dense.vectors(:,selected),direction.E);
    history(iScale).basis = previous;
    history(iScale).frequency = columnRayleighQuotients( ...
        previous,direction.E,1i*direction.J);
end
reference = history(end);
reference.history = history;
end

function dense = physicalEigensystem(direction,stationary)
E = direction.E;
R = chol((E+E')/2);
Yg = R*stationary;
if isempty(Yg)
    complement = eye(size(E));
else
    [complete,~] = qr(Yg);
    complement = complete(:,size(Yg,2)+1:end);
end
K = R'\(1i*direction.J/R);
reduced = complement'*K*complement;
[vectors,form] = schur((reduced+reduced')/2,"complex");
frequency = real(diag(form));
[frequency,order] = sort(frequency);
vectors = R\(complement*vectors(:,order));
dense = struct("vectors",energyNormalizeColumns(vectors,E), ...
    "frequency",frequency);
end

function dense = reducedPhysicalEigensystem(X,stationary,direction)
E = direction.E;
H = X'*E*X;
J = X'*direction.J*X;
stationaryCoordinate = H\(X'*E*stationary);
R = chol((H+H')/2);
Yg = R*stationaryCoordinate;
if isempty(Yg)
    complement = eye(size(H));
else
    [complete,~] = qr(Yg);
    complement = complete(:,size(Yg,2)+1:end);
end
K = R'\(1i*J/R);
reduced = complement'*K*complement;
[vectors,form] = schur((reduced+reduced')/2,"complex");
frequency = real(diag(form));
[frequency,order] = sort(frequency);
coordinates = R\(complement*vectors(:,order));
dense = struct("vectors",energyNormalizeColumns(X*coordinates,E), ...
    "frequency",frequency);
end

function selected = selectByOverlap(vectors,reference,E,count)
overlap = abs(vectors'*E*reference).^2;
score = sum(overlap,2);
[~,order] = sort(score,"descend");
selected = sort(order(1:min(count,numel(order))));
end

function diagnostics = physicalDiagnostics(c,direction,basis,frequency)
H = direction.E;
A = 1i*direction.J;
R = chol((H+H')/2);
residual = A*basis-(H*basis).*frequency.';
ritz = vecnorm(R'\residual,2,1).' ...
    ./max(norm(R'\(A/R),2)+abs(frequency),realmin);
trustedRows = find(repmat(c.layout.trustedHorizontalModes,c.nZ,1));
weightedQ = sqrt(c.apvVerticalWeight(trustedRows)) ...
    .*direction.QProjected(trustedRows,:);
apv = vecnorm(weightedQ*basis,2,1).' ...
    /max(norm(weightedQ/R,2),realmin);
bottomResidual = -1i*(direction.B*basis).*frequency.' ...
    -direction.R*basis;
bottomScale = abs(frequency)*norm(direction.B/R,2) ...
    +norm(direction.R/R,2);
bottom = vecnorm(bottomResidual,2,1).'./max(bottomScale,realmin);
strong = strongModeDiagnostics(c,direction,basis,frequency);
diagnostics = struct("maximumRitzResidual",max(ritz,[],"all"), ...
    "maximumAPVDefect",max(apv,[],"all"), ...
    "maximumBottomDefect",max(bottom,[],"all"), ...
    "maximumStrongResidual",strong.maximumResidual);
end

function diagnostics = strongModeDiagnostics(c,direction,C,frequency)
rawState = c.N*C;
pressure = direction.pressureMap*C;
stateTendency = -1i*rawState.*frequency.';
residual = direction.matrices.S*[stateTendency;pressure] ...
    -direction.matrices.F*C;
terms = {direction.matrices.S*[stateTendency;pressure], ...
    -direction.matrices.F*C};
scale = zeros(size(residual,2),1);
for iTerm = 1:numel(terms)
    scale = scale+vecnorm(terms{iTerm},2,1).';
end
defect = vecnorm(residual,2,1).'./max(scale,realmin);
diagnostics = struct("maximumResidual",max(defect,[],"all"));
end

function [coordinate,defect] = embedState(c,iHorizontal,state)
weight = c.quadrature.weight;
uCoefficient = weightedFit(c.spaces.F,state.u,weight);
vCoefficient = weightedFit(c.spaces.F,state.v,weight);
wCoefficient = weightedFit(c.spaces.G,state.w,weight);
etaCoefficient = weightedFit(c.spaces.H,state.eta,weight);
rawBlock = [uCoefficient;vCoefficient;wCoefficient;etaCoefficient];
rawRows = (iHorizontal-1)*c.nXBlock+(1:c.nXBlock);
admissible = c.layout.admissibleRanges{iHorizontal};
localBasis = c.N(rawRows,admissible);
coordinate = zeros(size(c.N,2),1);
coordinate(admissible) = localBasis\rawBlock;
represented = localBasis*coordinate(admissible);
defect = norm(represented-rawBlock)/max(norm(rawBlock),realmin);
end

function coefficient = weightedFit(reconstruction,values,weight)
coefficient = (reconstruction'*(weight.*reconstruction)) ...
    \(reconstruction'*(weight.*values));
end

function [uColumns,vColumns,wColumns,etaColumns] = componentColumns(c)
uColumns = zeros(c.nK*c.nF,1);
vColumns = zeros(c.nK*c.nF,1);
wColumns = zeros(c.nK*c.nG,1);
etaColumns = zeros(c.nK*c.nH,1);
for iK = 1:c.nK
    block = (iK-1)*c.nXBlock;
    uColumns((iK-1)*c.nF+(1:c.nF)) = block+(1:c.nF);
    vColumns((iK-1)*c.nF+(1:c.nF)) = block+c.nF+(1:c.nF);
    wColumns((iK-1)*c.nG+(1:c.nG)) = block+2*c.nF+(1:c.nG);
    etaColumns((iK-1)*c.nH+(1:c.nH)) = ...
        block+2*c.nF+c.nG+(1:c.nH);
end
end

function values = energyNormalizeColumns(values,E)
if isempty(values)
    return
end
R = chol((E+E')/2);
[~,S,V] = svd(R*values,"econ");
singularValues = diag(S);
tolerance = max(size(values))*eps(max(singularValues))*100;
rankValue = nnz(singularValues > tolerance);
values = values*V(:,1:rankValue)./singularValues(1:rankValue).';
end

function value = projectorDefect(first,second,E)
if size(first,2) ~= size(second,2)
    value = Inf;
    return
end
R = chol((E+E')/2);
first = R*energyNormalizeColumns(first,E);
second = R*energyNormalizeColumns(second,E);
value = norm(first*first'-second*second',"fro") ...
    /max(norm(first*first',"fro")+norm(second*second',"fro"),realmin);
end

function value = sortedFrequencyDefect(first,second)
first = sort(real(first));
second = sort(real(second));
if numel(first) ~= numel(second)
    value = Inf;
else
    value = norm(first-second) ...
        /max(norm(first)+norm(second),realmin);
end
end

function value = columnRayleighQuotients(X,H,A)
numerator = sum(conj(X).*(A*X),1);
denominator = sum(conj(X).*(H*X),1);
value = real(numerator./denominator).';
end

function value = normalizedProduct(operator,state)
value = norm(operator*state,"fro") ...
    /max(norm(operator,"fro")*norm(state,"fro"),realmin);
end

function value = subspaceConjugacyDefect(X,H,conjugateIndex)
n = size(H,1);
C = sparse((1:n)',conjugateIndex,1,n,n);
P = X*(X'*H);
value = norm(P*C-C*conj(P),"fro") ...
    /max(2*norm(P,"fro"),realmin);
end

function value = relativeDifference(first,second)
value = norm(first-second,"fro") ...
    /max(norm(first,"fro")+norm(second,"fro"),realmin);
end

