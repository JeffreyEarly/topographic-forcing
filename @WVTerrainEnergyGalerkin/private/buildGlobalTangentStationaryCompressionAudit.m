function [audit,cache] = loadAuditCache(problem,directory,configuration)
audit = [];
cache = emptyCacheDiagnostics(directory);
if directory == ""
    cache.numberOfMisses = 1;
    cache.records = cacheRecord("disabled","","",0,0,0);
    return
end
if ~isfolder(directory)
    mkdir(directory);
end
schema = "global-tangent-stationary-cache-v1";
key = cacheKey(problem,configuration,schema);
path = string(fullfile(directory,"audit-"+key+".mat"));
cache.key = key;
cache.path = path;
if ~isfile(path)
    cache.numberOfMisses = 1;
    cache.records = cacheRecord("miss",key,path,0,0,0);
    return
end
try
    loaded = load(path,"entry");
    entry = loaded.entry;
    if entry.schema ~= schema || entry.key ~= key
        cache.numberOfInvalidations = 1;
        cache.numberOfMisses = 1;
        cache.records = cacheRecord("invalidated",key,path,0,0,0);
        return
    end
    audit = entry.audit;
    information = dir(path);
    cache.numberOfHits = 1;
    cache.bytes = information.bytes;
    cache.secondsSaved = entry.buildSeconds;
    cache.records = cacheRecord( ...
        "hit",key,path,information.bytes,entry.buildSeconds, ...
        entry.buildSeconds);
catch
    cache.numberOfInvalidations = 1;
    cache.numberOfMisses = 1;
    cache.records = cacheRecord("invalidated",key,path,0,0,0);
end
end

function audit = saveAuditCache(audit,directory,configuration,cache, ...
    buildSeconds)
if directory == ""
    return
end
schema = "global-tangent-stationary-cache-v1";
key = cache.key;
path = cache.path;
entry = struct("schema",schema,"key",key, ...
    "configuration",configuration,"buildSeconds",buildSeconds, ...
    "created",string(datetime("now","TimeZone","UTC")), ...
    "audit",audit);
temporary = string(tempname(directory))+".mat";
cleanup = onCleanup(@()deleteIfPresent(temporary));
save(temporary,"entry","-v7.3");
movefile(temporary,path,"f");
clear cleanup
information = dir(path);
audit.cache.numberOfMisses = 1;
audit.cache.bytes = information.bytes;
audit.cache.secondsSaved = buildSeconds;
audit.cache.records = cacheRecord( ...
    "miss",key,path,information.bytes,buildSeconds,0);
end

function cache = emptyCacheDiagnostics(directory)
cache = struct("enabled",directory ~= "","directory",directory, ...
    "key","","path","","records",struct([]), ...
    "numberOfHits",0,"numberOfMisses",0, ...
    "numberOfInvalidations",0,"bytes",0,"secondsSaved",0);
end

function record = cacheRecord(status,key,path,bytes,buildSeconds,secondsSaved)
record = struct("status",status,"key",key,"path",path, ...
    "bytes",bytes,"buildSeconds",buildSeconds, ...
    "secondsSaved",secondsSaved);
end

function key = cacheKey(problem,configuration,schema)
engine = java.security.MessageDigest.getInstance("SHA-256");
updateDigest(engine,uint8(char(schema)));
updateDigest(engine,uint8(char(jsonencode(configuration))));
files = [string(mfilename("fullpath"))+".m"; ...
    fullfile(fileparts(fileparts(mfilename("fullpath"))), ...
    "auditGlobalTangentStationaryCompression.m"); ...
    fullfile(fileparts(fileparts(mfilename("fullpath"))), ...
    "auditAnalyticGlobalTangentStationaryCompression.m"); ...
    fullfile(fileparts(mfilename("fullpath")), ...
    "factorGlobalTangentStationarySpace.m"); ...
    fullfile(fileparts(mfilename("fullpath")), ...
    "buildZeroTraceGeostrophicVerticalFamily.m"); ...
    fullfile(fileparts(mfilename("fullpath")), ...
    "buildAnalyticZeroTraceGeostrophicVerticalFamily.m"); ...
    string(which("IMSolverSpectral")); ...
    string(which("IMInternalModes")); ...
    string(which("IMBoundaryCondition"))];
if any(files == "")
    error("WVTerrainEnergyGalerkin:MissingGlobalTangentProvider", ...
        "The isolated InternalModesEVP provider must be on the MATLAB path.")
end
for iFile = 1:numel(files)
    updateDigest(engine,uint8(fileread(files(iFile))));
end
wvt = problem.originatingTransform;
updateDigest(engine,typecast(double([wvt.Lx wvt.Ly wvt.Lz ...
    wvt.Nx wvt.Ny wvt.Nz wvt.f wvt.g wvt.rho0]),"uint8"));
updateDigest(engine,typecast(double(problem.topographicHeight(:)),"uint8"));
z = linspace(-wvt.Lz,0,max(17,2*wvt.Nz+1)).';
N2 = wvt.N2Function(z);
if isscalar(N2)
    N2 = repmat(N2,size(z));
end
updateDigest(engine,typecast(double(N2(:)),"uint8"));
digest = typecast(engine.digest(),"uint8");
key = lower(join(compose("%02x",digest),""));
end

function updateDigest(engine,bytes)
engine.update(bytes);
end

